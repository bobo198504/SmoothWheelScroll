// 装置分类对拍探针：触控板的"甩尾"数据会不会被误判成无级鼠标（从而混进模型）？
//
// 分类规则（src/device.h）：
//   * 整 120            -> kNotched（进模型）
//   * 亚格值，最近窗口里"不同幅度数 <= 1"(全都一样) 且 >=3 个样本 -> kFreeSpin（进模型）
//   * 亚格值，幅度有变化 -> kTouchpad（放行）
//   * 样本 < 3          -> kUnknown（放行）
//
// 所以风险是：**一段"值都相同"的小 delta** 会被当成无级鼠标。触控板甩尾/匀速段可能长这样。
// 本探针把几种典型的触控板数据流喂进去，打印每条消息的分类，看有没有哪一条"漏进模型"。
//
//   g++ -std=c++17 -O2 -I../src -o 分类.exe device_swipe_probe.cpp && ./分类.exe
#include "device.h"
#include <cstdio>
#include <initializer_list>

static const char *名(Device d) { return DeviceName(d); }
static const char *进模型(Device d)
{
  return (d == Device::kNotched || d == Device::kFreeSpin) ? "★进模型" : "  放行";
}

// 喂一串 delta，打印每条的分类（extraInfo=0，即没有触摸标记，最坏情况）
static void 跑(const char *标题, std::initializer_list<int> 流)
{
  DeviceTracker t;
  t.Reset();
  printf("== %s ==\n   ", 标题);
  for (int d : 流)
  {
    const Device v = t.Feed(d, 0); // 没有 OS 触摸标记
    printf("%d>%s%s  ", d, 名(v), 进模型(v));
  }
  printf("\n\n");
}

int main()
{
  printf("把几种触控板数据流喂进分类器（都不带 OS 触摸标记，最坏情况）\n\n");

  跑("触控板甩尾：逐渐减速的小值（典型）", {40, 36, 32, 28, 24, 20, 16, 12, 8, 4});
  跑("触控板甩尾收尾：只剩几个相同的极小值", {20, 16, 12, 8, 8, 8, 8, 8});
  跑("触控板慢速匀速段：值全都一样（8 个以上）", {12, 12, 12, 12, 12, 12, 12, 12, 12, 12, 12, 12});
  跑("★同一次手势中途翻转：前不规则、后恒定",
     {30, 28, 26, 24, 22, 20, 18, 16, 12, 12, 12, 12, 12, 12, 12, 12, 12, 12});
  跑("触控板起步：两个不同的值", {18, 14, 18, 14, 18, 14});
  跑("无级鼠标（真）：固定 15", {15, 15, 15, 15, 15, 15});
  跑("无级鼠标（真）：两个档 15/30", {15, 30, 15, 30, 15, 30});
  跑("普通鼠标：整格 120", {120, 120, 120, 120});

  printf("说明：只要某条显示 ★进模型，那段触控板数据就会被动画——这是用户说的\n"
         "\"甩尾混进模型\"。若整列都是放行，则触控板没有漏进去。\n");
  return 0;
}
